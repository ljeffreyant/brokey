import * as fontkit from 'fontkit';
import fs from 'node:fs';
import path from 'node:path';

const root = path.join(__dirname, '..');
const font = fontkit.openSync(
  path.join(root, 'node_modules/@expo-google-fonts/bricolage-grotesque/800ExtraBold/BricolageGrotesque_800ExtraBold.ttf'),
) as fontkit.Font;

function glyphs(text: string, size: number) {
  const run = font.layout(text);
  const k = size / font.unitsPerEm;
  let x = 0;
  const out: { d: string; x1: number; y1: number; x2: number; y2: number }[] = [];
  run.glyphs.forEach((g, i) => {
    const p = g.path.transform(k, 0, 0, -k, x + run.positions[i].xOffset * k, 0);
    const bb = p.bbox;
    out.push({
      d: p.toSVG(),
      x1: +bb.minX.toFixed(1),
      y1: +bb.minY.toFixed(1),
      x2: +bb.maxX.toFixed(1),
      y2: +bb.maxY.toFixed(1),
    });
    x += run.positions[i].xAdvance * k;
  });
  return out;
}

const out = `// Generated by scripts/bake-glyphs.ts. Bricolage Grotesque ExtraBold outlines at size 100, baseline y=0.
export interface Glyph { d: string; x1: number; y1: number; x2: number; y2: number }
export const BROKEY_GLYPHS: Glyph[] = ${JSON.stringify(glyphs('Brokey', 100))};
export const HSP_GLYPHS: Glyph[] = ${JSON.stringify(glyphs('HSP', 100))};
`;
fs.writeFileSync(path.join(root, 'src/art/glyphs.ts'), out);
console.log('baked glyphs');
